"""Command-level publishing tests; each test uses a disposable site tree."""

import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import unittest


SCRIPT = Path(__file__).resolve().parents[1] / "tools" / "publish.py"
ARCHIVE = """<!doctype html><html><head><title>Archive</title></head><body>
<!-- Authored archive prose -->
<section id='chronological' class='archive-view archive-view-chrono'>
<h2>Chronological</h2><ul class='archive-list'></ul></section>
<section class='archive-view archive-view-category' id='by-category'>
<nav>Authored navigation</nav>
<h3 id='general' class='archive-category-heading'>General</h3>
<ul class='archive-list'></ul>
<h3 class='archive-category-heading' id='essay'>Essay</h3>
<ul class='archive-list'></ul></section>
<footer>Authored footer</footer></body></html>
"""
POST = """<!doctype html><html><head>
<title>Authored title</title></head><body><p>Prose &amp; punctuation.</p></body></html>
"""
GATE = """# Generated by tools/publish.py - do not edit.
# This post is a draft. Publishing it removes this file.
AuthType Basic
AuthName "jacobstephens.net draft preview"
AuthUserFile /var/www/.htpasswd-drafts
Require valid-user
"""


class PublishCommands(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        (self.root / "tools").mkdir()
        shutil.copyfile(SCRIPT, self.root / "tools" / "publish.py")
        (self.root / "posts").mkdir()
        self.data = {
            "categories": {"general": "General", "essay": "Essay"},
            "posts": [
                {"slug": "first", "title": "First", "date": "Older date",
                 "categories": ["general", "essay"], "status": "published"},
                {"slug": "second", "title": "Second", "date": "Newer date",
                 "categories": ["essay"], "status": "published"},
            ],
        }
        self.write_manifest()
        self.write("posts/index.html", ARCHIVE)
        for post in self.data["posts"]:
            self.write(f"posts/{post['slug']}/index.html", POST)

    def write(self, path, text):
        target = self.root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")

    def write_manifest(self):
        self.write("posts.json", json.dumps(self.data, ensure_ascii=False) + "\n")

    def run_cli(self, *args, **options):
        return subprocess.run(
            [sys.executable, str(self.root / "tools" / "publish.py"), *args],
            cwd="/", capture_output=True, text=True, **options,
        )

    def assert_success(self, *args):
        result = self.run_cli(*args)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        return result

    def snapshot(self):
        return {str(p.relative_to(self.root)): p.read_bytes()
                for p in self.root.rglob("*") if p.is_file()}

    def assert_rejected_without_writes(self, *args, message):
        before = self.snapshot()
        result = self.run_cli(*args)
        self.assertNotEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn(message, result.stderr)
        self.assertNotIn("is now", result.stdout)
        self.assertEqual(self.snapshot(), before)

    def test_missing_post_fails_check_without_writes(self):
        # Use the old script's exact archive spelling to isolate its missing-file bug.
        self.write("posts/index.html", ARCHIVE.replace("'", '"').replace(
            '<section id="chronological" class="archive-view archive-view-chrono">',
            '<section class="archive-view archive-view-chrono" id="chronological">',
        ).replace('<ul class="archive-list">', '            <ul class="archive-list">\n')
          .replace('</ul>', '            </ul>'))
        self.assert_success("build")
        (self.root / "posts/second/index.html").unlink()
        self.assert_rejected_without_writes("check", message="second/index.html")

    def test_malformed_archive_does_not_save_draft_status(self):
        self.write("posts/index.html", ARCHIVE.replace("id='chronological'", "id='broken'"))
        self.assert_rejected_without_writes("draft", "first", message="chronological")

    def test_missing_and_duplicate_archive_targets_fail_before_writes(self):
        general = "<h3 id='general' class='archive-category-heading'>General</h3>"
        cases = [
            (ARCHIVE.replace(general, ""), "general"),
            (ARCHIVE.replace(general, general + general), "general"),
            (ARCHIVE.replace(general + "\n<ul class='archive-list'></ul>", general), "general"),
            (ARCHIVE.replace("<ul class='archive-list'></ul>", "", 1), "chronological"),
            (ARCHIVE.replace("<h2>Chronological</h2>", "<ul class='archive-list'></ul>"), "chronological"),
            (ARCHIVE.replace("</section>", "</section><section id='chronological' class='archive-view-chrono'></section>", 1), "chronological"),
            (ARCHIVE.replace("id='by-category'", "id='missing'"), "by-category"),
            (ARCHIVE.replace("</body>", "<section id='by-category' class='archive-view-category'></section></body>"), "by-category"),
            (ARCHIVE.replace(general + "\n<ul", general + "<p>Unrelated prose</p>\n<ul"), "general"),
            (ARCHIVE.replace("<h2>Chronological</h2><ul", "<h2>Chronological</h2><div><ul")
             .replace("</ul></section>", "</ul></div></section>", 1), "chronological"),
            (ARCHIVE.replace("</ul>", "", 1), "chronological"),
            (ARCHIVE.replace("</section>", "", 1), "chronological"),
            (ARCHIVE.replace("</section>", "<ul class='archive-list'></ul></section>"), "chronological"),
        ]
        for html, message in cases:
            for args in [("check",), ("build",), ("draft", "first"), ("publish", "first")]:
                with self.subTest(message=message, html=html, args=args):
                    self.write("posts/index.html", html)
                    self.assert_rejected_without_writes(*args, message=message)

    def test_manifest_validation_is_actionable_and_read_only(self):
        valid = json.loads(json.dumps(self.data))
        cases = [(None, "root"), ([], "root"), ({}, "categories"),
                 ({"categories": [], "posts": []}, "categories"),
                 ({"categories": {}, "posts": {}}, "posts"),
                 ({"categories": {}, "posts": [None]}, "posts[0]")]
        for category, label in [("../bad", "Bad"), ("Upper", "Bad"), ("general", " "), ("general", 3)]:
            data = json.loads(json.dumps(valid))
            data["categories"] = {category: label}
            cases.append((data, "categories."))
        for key, value in [
            ("slug", "../escape"), ("slug", "has/slash"), ("slug", "Upper"),
            ("slug", "a--b"), ("slug", ""), ("slug", None), ("slug", []),
            ("title", " "), ("title", False), ("date", None), ("date", ""),
            ("status", "Published"), ("status", "unlisted"), ("status", []),
            ("categories", "general"), ("categories", ["missing"]),
            ("categories", ["general", "general"]), ("categories", [[]]),
        ]:
            data = json.loads(json.dumps(valid))
            data["posts"][0][key] = value
            cases.append((data, key))
        for key in ["slug", "title", "date", "status", "categories"]:
            data = json.loads(json.dumps(valid))
            del data["posts"][0][key]
            cases.append((data, key))
        duplicate = json.loads(json.dumps(valid))
        duplicate["posts"].append(duplicate["posts"][0])
        cases.append((duplicate, "duplicate slug"))
        for data, message in cases:
            for args in [("list",), ("status", "first"), ("check",), ("build",), ("draft", "first"), ("publish", "first")]:
                with self.subTest(data=data, args=args):
                    self.data = data
                    self.write_manifest()
                    self.assert_rejected_without_writes(*args, message=message)
        for source, message in [('{', "posts.json"),
                                ('{"categories": {}, "categories": {}, "posts": []}', "duplicate key")]:
            self.write("posts.json", source)
            self.assert_rejected_without_writes("build", message=message)

    def test_overlapping_archive_targets_fail_without_writes(self):
        nested = ARCHIVE.replace(
            "<h2>Chronological</h2><ul class='archive-list'></ul></section>",
            "<h2>Chronological</h2><ul class='archive-list'><li>",
        ).replace("<footer>", "</li></ul></section><footer>")
        self.write("posts/index.html", nested)
        for args in [("check",), ("build",), ("draft", "first"), ("publish", "first")]:
            self.assert_rejected_without_writes(*args, message="overlapping")

    def test_unknown_slugs_and_manifest_only_commands(self):
        (self.root / "posts/index.html").unlink()
        before = self.snapshot()
        default = self.assert_success().stdout
        self.assertEqual(default, self.assert_success("list").stdout)
        self.assertLess(default.index("/posts/first/"), default.index("/posts/second/"))
        self.assertEqual(json.loads(self.assert_success("status", "first").stdout), self.data["posts"][0])
        self.assertEqual(self.snapshot(), before)
        for command in ["status", "draft", "publish"]:
            self.assert_rejected_without_writes(command, "unknown", message="unknown slug: unknown")
            self.assert_rejected_without_writes(command, message="unknown slug: None")

    def test_invalid_post_heads_and_robots_fail_before_writes(self):
        cases = [
            (POST.replace("<head>", "").replace("</head>", ""), "head"),
            (POST.replace("<head>", "<head><head></head>"), "head"),
            (POST.replace("</head>", ""), "head"),
            (POST.replace("</head>", "</head></head>"), "head"),
            (POST.replace("<head>", "<head/>"), "head"),
            (POST.replace("<head>", "<body><head>"), "head"),
            (POST.replace("</head>", "").replace("</html>", "</head></html>"), "head"),
            (POST.replace("<head>", "<head>Unexpected prose"), "head"),
            (POST.replace("<head>", "<body></body><head>"), "head"),
            (POST.replace("</head>", "<meta name='robots'><meta NAME=ROBOTS></head>"), "robots"),
            (POST.replace("</body>", "<meta name='robots'></body>"), "robots"),
        ]
        for html, message in cases:
            self.write("posts/second/index.html", html)
            for args in [("check",), ("build",), ("draft", "first"), ("publish", "first")]:
                with self.subTest(html=html, args=args):
                    self.assert_rejected_without_writes(*args, message=message)

    def test_late_read_failures_leave_all_files_unchanged(self):
        target = self.root / "posts/second/index.html"
        for contents in [None, b"\xff"]:
            if contents is None:
                target.unlink()
            else:
                target.write_bytes(contents)
            for args in [("check",), ("build",), ("draft", "first"), ("publish", "first")]:
                self.assert_rejected_without_writes(*args, message="second/index.html")
        target.write_text(POST)
        gate = self.root / "posts/second/.htaccess"
        gate.mkdir()
        self.assert_rejected_without_writes("draft", "first", message="second/.htaccess")
        gate.rmdir()
        gate.symlink_to("missing")
        self.assert_rejected_without_writes("draft", "first", message="regular file")

    def test_transitions_reconcile_all_outputs_and_preserve_prose(self):
        self.assert_success("build")
        original_page = (self.root / "posts/first/index.html").read_bytes()
        self.assert_success("draft", "first")
        saved = json.loads((self.root / "posts.json").read_text())
        self.assertEqual(saved["posts"][0]["status"], "draft")
        self.assertEqual((self.root / "posts/first/.htaccess").read_text(), GATE)
        draft_page = (self.root / "posts/first/index.html").read_text()
        self.assertIn('<meta name="robots" content="noindex, nofollow"></head>', draft_page)
        self.assertEqual(draft_page.replace('<meta name="robots" content="noindex, nofollow">', ''), POST)
        archive = (self.root / "posts/index.html").read_text()
        self.assertNotIn('/posts/first/', archive)
        self.assertEqual(archive.count('/posts/second/'), 2)
        self.assert_success("check")
        # A status command must also reconcile unrelated drift, via the same plan.
        self.write("posts/second/.htaccess", "stale published gate")
        self.assert_success("publish", "first")
        self.assertFalse((self.root / "posts/first/.htaccess").exists())
        self.assertFalse((self.root / "posts/second/.htaccess").exists())
        self.assertEqual((self.root / "posts/first/index.html").read_bytes(), original_page)
        saved = json.loads((self.root / "posts.json").read_text())
        self.assertEqual(saved["posts"][0]["status"], "published")
        archive = (self.root / "posts/index.html").read_text()
        lists = re.findall(r"<ul\b[^>]*>(.*?)</ul>", archive, re.S)
        self.assertEqual([re.findall(r'href="(/posts/[^\"]+)"', listing) for listing in lists],
                         [["/posts/first/", "/posts/second/"], ["/posts/first/"], ["/posts/first/", "/posts/second/"]])
        self.assertNotIn('href="#general"', lists[1])
        self.assertIn('href="#essay"', lists[1])
        self.assertNotIn('href="#essay"', lists[2])
        self.assertIn('href="#general"', lists[2])
        # Only list interiors are owned; headings, prose and navigation are exact.
        empty_lists = lambda source: re.sub(r"(<ul\b[^>]*>).*?(</ul>)", r"\1\2", source, flags=re.S)
        self.assertEqual(empty_lists(archive), empty_lists(ARCHIVE))
        self.assert_success("check")

    def test_build_repairs_drift_check_is_read_only_and_build_is_idempotent(self):
        self.data["posts"][0]["status"] = "draft"
        self.write_manifest()
        self.write("posts/second/.htaccess", "stale gate")
        self.assert_rejected_without_writes("check", message="STALE")
        self.assert_success("build")
        self.assertEqual((self.root / "posts/first/.htaccess").read_text(), GATE)
        self.assertFalse((self.root / "posts/second/.htaccess").exists())
        before = self.snapshot()
        metadata = lambda: {str(p): (p.stat().st_ino, p.stat().st_mtime_ns, p.stat().st_mode)
                            for p in self.root.rglob("*") if p.is_file()}
        original_metadata = metadata()
        self.assertIn("already up to date", self.assert_success("build").stdout)
        self.assert_success("check")
        self.assertEqual(self.snapshot(), before)
        self.assertEqual(metadata(), original_metadata)

    def test_robots_attribute_variations_and_missing_theme_color(self):
        for robot in ["<META content='index' NAME = 'RoBoTs' />",
                      '<meta\ncontent = "anything"\nname=robots>',
                      '<meta name="robots" content="noindex, nofollow">', ""]:
            with self.subTest(robot=robot):
                authored = POST.replace("</head>", robot + "</head>")
                self.write("posts/first/index.html", authored)
                self.assert_success("draft", "first")
                result = (self.root / "posts/first/index.html").read_text()
                self.assertEqual(result.count('<meta name="robots" content="noindex, nofollow">'), 1)
                self.assertEqual(result.replace('<meta name="robots" content="noindex, nofollow">', ''), POST)
                self.assert_success("check")
                self.assert_success("publish", "first")
                self.assertEqual((self.root / "posts/first/index.html").read_text(), POST)

    def test_plain_text_escaping_and_empty_categories(self):
        self.data["posts"][0]["title"] = '<script>alert("x")</script> & literal'
        self.data["posts"][0]["date"] = '<time> & "date"'
        self.data["categories"]["essay"] = 'Essays < & > "quoted"'
        self.data["posts"][1]["categories"] = []
        self.write_manifest()
        self.assert_success("build")
        archive = (self.root / "posts/index.html").read_text()
        self.assertIn('&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt; &amp; literal', archive)
        self.assertIn('&lt;time&gt; &amp; &quot;date&quot;', archive)
        self.assertIn('Essays &lt; &amp; &gt; &quot;quoted&quot;', archive)
        self.assertNotIn('<script>', archive)
        self.assertEqual(archive.count('/posts/second/'), 1)
        self.assert_success("check")

    def test_source_positions_preserve_crlf_and_unicode_prose(self):
        page = POST.replace("<title>", "<!-- Prose \u2028 separator -->\n<title>").replace("\n", "\r\n")
        self.write("posts/first/index.html", page)
        self.assert_success("draft", "first")
        actual = (self.root / "posts/first/index.html").read_bytes()
        self.assertIn(b'<meta name="robots" content="noindex, nofollow"></head>', actual)
        self.assertEqual(actual.replace(b'<meta name="robots" content="noindex, nofollow">', b''),
                         page.encode("utf-8"))
        self.assert_success("check")

    def test_atomic_replacements_preserve_permissions_and_new_gate_uses_umask(self):
        archive = self.root / "posts/index.html"
        page = self.root / "posts/first/index.html"
        archive.chmod(0o640)
        page.chmod(0o604)
        result = self.run_cli("draft", "first", umask=0o027)
        self.assertEqual(result.returncode, 0, result.stderr)
        gate = self.root / "posts/first/.htaccess"
        self.assertEqual(gate.stat().st_mode & 0o777, 0o640)
        self.assertEqual(archive.stat().st_mode & 0o777, 0o640)
        self.assertEqual(page.stat().st_mode & 0o777, 0o604)
        gate.chmod(0o600)
        gate.write_text("stale gate")
        self.assert_success("build")
        self.assertEqual(gate.stat().st_mode & 0o777, 0o600)
        self.assertFalse(list(self.root.rglob("*.tmp")))

    @unittest.skipIf(os.geteuid() == 0, "permission failures require an unprivileged process")
    def test_write_failure_creates_gate_first_and_reports_no_success(self):
        posts = self.root / "posts"
        posts.chmod(0o555)
        try:
            manifest = (self.root / "posts.json").read_bytes()
            result = self.run_cli("draft", "first")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("Permission denied", result.stderr)
            self.assertNotIn("is now", result.stdout)
            self.assertEqual((self.root / "posts.json").read_bytes(), manifest)
            self.assertEqual((self.root / "posts/first/.htaccess").read_text(), GATE)
            self.assertEqual((self.root / "posts/index.html").read_text(), ARCHIVE)
            self.assertFalse(list(self.root.rglob("*.tmp")))
        finally:
            posts.chmod(0o755)

    @unittest.skipIf(os.geteuid() == 0, "permission failures require an unprivileged process")
    def test_failed_publish_keeps_gate_until_manifest_is_saved(self):
        self.assert_success("draft", "first")
        manifest = (self.root / "posts.json").read_bytes()
        self.root.chmod(0o555)
        try:
            result = self.run_cli("publish", "first")
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("Permission denied", result.stderr)
            self.assertNotIn("is now", result.stdout)
            self.assertEqual((self.root / "posts.json").read_bytes(), manifest)
            self.assertEqual((self.root / "posts/first/.htaccess").read_text(), GATE)
            self.assertFalse(list(self.root.rglob("*.tmp")))
        finally:
            self.root.chmod(0o755)
        self.assert_success("build")
        self.assert_success("check")


if __name__ == "__main__":
    unittest.main()
