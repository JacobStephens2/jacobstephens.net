"""Reconcile registered posts with posts.json, validating before any write.

    python3 tools/publish.py list                 show every post and status
    python3 tools/publish.py status <slug>        show one post
    python3 tools/publish.py draft <slug>         unpublish
    python3 tools/publish.py publish <slug>       publish
    python3 tools/publish.py build                repair generated output
    python3 tools/publish.py check                read-only validation and drift check

The manifest owns post order and status. The publisher owns archive list contents,
post robots directives and draft password gates; all other HTML remains authored.
Every reconciliation command reads and validates the managed tree, then computes
the same desired-file plan. Application creates gates first and removes them last.
An OS write failure may leave a partial application; rerun build after repair.
"""

from dataclasses import dataclass, field
from html import escape
from html.parser import HTMLParser
import json
import os
from pathlib import Path
import re
import secrets
import stat
import sys


ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "posts.json"
ARCHIVE = ROOT / "posts" / "index.html"
ROBOTS = '<meta name="robots" content="noindex, nofollow">'
IDENTIFIER = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")

# This public configuration contains only the location of the server's password
# file. If the file is missing, Apache refuses access to the draft.
DRAFT_HTPASSWD = "/var/www/.htpasswd-drafts"
DRAFT_HTACCESS = (
    "# Generated by tools/publish.py - do not edit.\n"
    "# This post is a draft. Publishing it removes this file.\n"
    "AuthType Basic\n"
    'AuthName "jacobstephens.net draft preview"\n'
    f"AuthUserFile {DRAFT_HTPASSWD}\n"
    "Require valid-user\n"
)


class InvalidSite(ValueError):
    """An actionable manifest or managed-HTML validation failure."""


@dataclass
class FileSnapshot:
    path: Path
    contents: bytes | None
    mode: int | None

    @classmethod
    def read(cls, path, optional=False):
        try:
            metadata = path.lstat()
        except FileNotFoundError:
            if optional:
                return cls(path, None, None)
            raise InvalidSite(f"{path}: required file is missing")
        if not stat.S_ISREG(metadata.st_mode):
            raise InvalidSite(f"{path}: expected a readable regular file")
        return cls(path, path.read_bytes(), stat.S_IMODE(metadata.st_mode))

    def text(self):
        try:
            return self.contents.decode("utf-8")
        except UnicodeError as error:
            raise InvalidSite(f"{self.path}: expected UTF-8 text: {error}") from error


@dataclass
class Change:
    original: FileSnapshot
    desired: bytes | None

    def apply(self):
        path = self.original.path
        if self.desired is None:
            path.unlink()
            return
        temporary = path.with_name(f".{path.name}.{secrets.token_hex(8)}.tmp")
        try:
            # New gates use ordinary creation permissions: 0666 and the umask.
            descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o666)
            with os.fdopen(descriptor, "wb") as output:
                output.write(self.desired)
                if self.original.mode is not None:
                    os.fchmod(output.fileno(), self.original.mode)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def changed_files(desired_files):
    return [Change(original, desired) for original, desired in desired_files
            if original.contents != desired]


def unique_json_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise InvalidSite(f"posts.json: duplicate key {key!r}")
        result[key] = value
    return result


def load_manifest(snapshot):
    try:
        data = json.loads(snapshot.text(), object_pairs_hook=unique_json_object)
    except json.JSONDecodeError as error:
        raise InvalidSite(f"posts.json: {error}") from error

    def require(condition, location, expectation):
        if not condition:
            raise InvalidSite(f"posts.json: {location}: {expectation}")

    def identifier(value):
        return isinstance(value, str) and IDENTIFIER.fullmatch(value) is not None

    def text(value):
        return isinstance(value, str) and bool(value.strip())

    require(isinstance(data, dict), "root", "expected an object")
    labels = data.get("categories")
    require(isinstance(labels, dict), "categories", "expected an id-to-label object")
    for category, label in labels.items():
        require(identifier(category), f"categories.{category}", "expected a lowercase hyphenated identifier")
        require(text(label), f"categories.{category}", "expected a nonempty text label")
    posts = data.get("posts")
    require(isinstance(posts, list), "posts", "expected a list")
    slugs = set()
    for index, post in enumerate(posts):
        location = f"posts[{index}]"
        require(isinstance(post, dict), location, "expected an object")
        slug = post.get("slug")
        require(identifier(slug), f"{location}.slug", "expected a lowercase hyphenated single-segment slug")
        require(slug not in slugs, f"{location}.slug", f"duplicate slug {slug!r}")
        slugs.add(slug)
        for key in ("title", "date"):
            require(text(post.get(key)), f"{location}.{key} ({slug})", "expected nonempty text")
        require(post.get("status") in ("draft", "published"), f"{location}.status ({slug})",
                "expected exactly 'draft' or 'published'")
        categories = post.get("categories")
        require(isinstance(categories, list), f"{location}.categories ({slug})", "expected a list")
        seen = set()
        for category in categories:
            require(identifier(category), f"{location}.categories ({slug})", "expected category identifiers")
            require(category in labels, f"{location}.categories ({slug})", f"undeclared category {category!r}")
            require(category not in seen, f"{location}.categories ({slug})", f"duplicate category {category!r}")
            seen.add(category)
    return data


@dataclass(eq=False)
class Element:
    tag: str
    attrs: dict
    start: int
    start_end: int
    parent: "Element | None"
    children: list = field(default_factory=list)
    end_start: int | None = None

    def has_class(self, name):
        return name in (self.attrs.get("class") or "").split()


class Document(HTMLParser):
    """Index source spans; never serialize authored HTML through a DOM."""

    VOID_TAGS = set("area base br col embed hr img input link meta param source track wbr".split())

    def __init__(self, html, path):
        super().__init__(convert_charrefs=True)
        self.html = html
        self.path = path
        self.elements = []
        self.stack = []
        self.unmatched_heads = 0
        self.head_has_text = False
        self.lines = [0]
        # HTMLParser counts only LF, whereas splitlines also splits prose at
        # Unicode separators and bare CR, moving source spans into authored text.
        self.lines.extend(match.end() for match in re.finditer("\n", html))
        self.feed(html)
        self.close()

    def fail(self, message):
        raise InvalidSite(f"{self.path}: {message}")

    def source_offset(self):
        line, column = self.getpos()
        return self.lines[line - 1] + column

    def handle_starttag(self, tag, attrs):
        for key in ("id", "class", "name"):
            if sum(name == key for name, _ in attrs) > 1:
                self.fail(f"ambiguous duplicate {key} attribute on <{tag}>")
        start = self.source_offset()
        parent = self.stack[-1] if self.stack else None
        element = Element(tag, dict(attrs), start, start + len(self.get_starttag_text()), parent)
        self.elements.append(element)
        if parent:
            parent.children.append(element)
        if tag not in self.VOID_TAGS:
            self.stack.append(element)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in self.VOID_TAGS:
            self.stack.pop()

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, -1, -1):
            element = self.stack[index]
            if element.tag == tag:
                element.end_start = self.source_offset()
                del self.stack[index:]
                return
        if tag == "head":
            self.unmatched_heads += 1

    def handle_data(self, data):
        if self.stack and self.stack[-1].tag == "head" and data.strip(" \t\n\f\r"):
            self.head_has_text = True

    def require_closed(self, element, description):
        if element.end_start is None:
            self.fail(f"{description}: missing closing </{element.tag}>")
        return element

    def target(self, identifier, tag, class_name):
        matches = [node for node in self.elements if node.attrs.get("id") == identifier]
        if len(matches) != 1:
            self.fail(f"{identifier}: expected exactly one target, found {len(matches)}")
        node = matches[0]
        if node.tag != tag or not node.has_class(class_name):
            self.fail(f"{identifier}: expected <{tag}> with class {class_name}")
        return self.require_closed(node, identifier)

    def replace(self, spans):
        ordered = sorted(spans)
        if any(right[0] < left[1] for left, right in zip(ordered, ordered[1:])):
            self.fail("overlapping owned HTML targets; archive lists must be separate")
        result = self.html
        for start, end, replacement in reversed(ordered):
            result = result[:start] + replacement + result[end:]
        return result


def entry(post, labels, skip=None):
    tail = "".join(f' &middot; <a href="#{category}">{escape(labels[category])}</a>'
                   for category in post["categories"] if category != skip)
    return (
        "                <li>\n"
        f'                    <a href="/posts/{post["slug"]}/">{escape(post["title"])}</a><br>\n'
        f'                    {escape(post["date"])}{tail}\n'
        "                </li>\n"
    )


def archive_html(snapshot, data):
    document = Document(snapshot.text(), snapshot.path)
    chronological = document.target("chronological", "section", "archive-view-chrono")
    category_view = document.target("by-category", "section", "archive-view-category")
    chronological_lists = [node for node in chronological.children
                           if node.tag == "ul" and node.has_class("archive-list")]
    if len(chronological_lists) != 1:
        document.fail(f"chronological: expected exactly one archive-list, found {len(chronological_lists)}")
    targets = [(chronological_lists[0], None)]
    for category in data["categories"]:
        heading = document.target(category, "h3", "archive-category-heading")
        if heading.parent is not category_view:
            document.fail(f"{category}: heading must be directly inside by-category")
        siblings = category_view.children
        index = siblings.index(heading) + 1
        following = siblings[index] if index < len(siblings) else None
        if following is None or following.tag != "ul" or not following.has_class("archive-list"):
            document.fail(f"{category}: heading must be followed by its archive-list")
        targets.append((following, category))
    category_lists = [node for node in category_view.children
                      if node.tag == "ul" and node.has_class("archive-list")]
    if set(category_lists) != {node for node, category in targets if category is not None}:
        document.fail("by-category: ambiguous archive-list without a declared category heading")

    published = [post for post in data["posts"] if post["status"] == "published"]
    spans = []
    for listing, category in targets:
        document.require_closed(listing, category or "chronological")
        items = "".join(entry(post, data["categories"], category) for post in published
                        if category is None or category in post["categories"])
        spans.append((listing.start_end, listing.end_start, "\n" + items + "            "))
    return document.replace(spans).encode("utf-8")


def post_html(snapshot, draft):
    document = Document(snapshot.text(), snapshot.path)
    heads = [node for node in document.elements if node.tag == "head"]
    if len(heads) != 1 or document.unmatched_heads:
        document.fail(f"expected exactly one head with one closing tag, found {len(heads)} heads")
    head = document.require_closed(heads[0], "head")
    if head.parent is not None and head.parent.tag != "html":
        document.fail("head must be directly inside html")
    # Body content implicitly closes a browser's head, even when a later literal
    # </head> appears. Do not insert robots after that implicit closing point.
    metadata_tags = {"base", "link", "meta", "title", "style", "script", "noscript", "template"}
    if document.head_has_text or any(child.tag not in metadata_tags for child in head.children):
        document.fail("head must contain only metadata, comments and whitespace")
    for child in head.children:
        if child.tag not in document.VOID_TAGS:
            document.require_closed(child, f"head <{child.tag}>")
    if any(node.tag == "body" and node.start < head.end_start for node in document.elements):
        document.fail("head must end before body content starts")
    robots = [node for node in document.elements if node.tag == "meta"
              and (node.attrs.get("name") or "").strip().lower() == "robots"]
    if len(robots) > 1:
        document.fail("expected at most one robots meta tag")
    spans = []
    if robots:
        robot = robots[0]
        if robot.parent is not head:
            document.fail("robots meta tag must be directly inside head")
        spans.append((robot.start, robot.start_end, ROBOTS if draft else ""))
    elif draft:
        spans.append((head.end_start, head.end_start, ROBOTS))
    return document.replace(spans).encode("utf-8")


def desired_plan(data, manifest, status_changed):
    # All reads, validation and rendering finish before a caller can apply changes.
    archive = FileSnapshot.read(ARCHIVE)
    pages = [(archive, archive_html(archive, data))]
    gates = []
    removals = []
    for post in data["posts"]:
        directory = ROOT / "posts" / post["slug"]
        page = FileSnapshot.read(directory / "index.html")
        draft = post["status"] == "draft"
        pages.append((page, post_html(page, draft)))
        gate = FileSnapshot.read(directory / ".htaccess", optional=True)
        if draft:
            gates.append((gate, DRAFT_HTACCESS.encode("utf-8")))
        else:
            removals.append((gate, None))
    manifest_changes = []
    if status_changed:
        serialized = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
        manifest_changes.append((manifest, serialized.encode("utf-8")))
    return changed_files(gates + pages + manifest_changes + removals)


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "list"
    slug = sys.argv[2] if len(sys.argv) > 2 else None
    manifest = FileSnapshot.read(MANIFEST)
    data = load_manifest(manifest)
    index = {post["slug"]: post for post in data["posts"]}

    if cmd == "list":
        drafts = [post for post in data["posts"] if post["status"] == "draft"]
        print(f"{len(data['posts'])} posts, {len(drafts)} draft\n")
        for post in data["posts"]:
            mark = "DRAFT " if post["status"] == "draft" else "      "
            print(f"  {mark}{post['date']:<20} {post['title'][:52]}")
            print(f"        /posts/{post['slug']}/")
        return

    if cmd in ("status", "draft", "publish") and slug not in index:
        raise InvalidSite(f"unknown slug: {slug}")
    if cmd == "status":
        print(json.dumps(index[slug], indent=2))
        return
    if cmd not in ("build", "check", "draft", "publish"):
        sys.exit(__doc__)

    status_changed = False
    if cmd in ("draft", "publish"):
        status = "draft" if cmd == "draft" else "published"
        status_changed = index[slug]["status"] != status
        index[slug]["status"] = status
    plan = desired_plan(data, manifest, status_changed)
    if cmd == "check":
        if plan:
            raise InvalidSite(
                "STALE: the site does not match posts.json:\n"
                + "\n".join(f"  {change.original.path.relative_to(ROOT)}" for change in plan)
                + "\nRun: python3 tools/publish.py build"
            )
        print("site matches posts.json")
        return

    for change in plan:
        change.apply()
    print("\n".join(f"  updated {change.original.path.relative_to(ROOT)}" for change in plan)
          or "  already up to date")
    if cmd in ("draft", "publish"):
        print(f"{slug} is now {index[slug]['status']}")


if __name__ == "__main__":
    try:
        main()
    except (InvalidSite, OSError) as error:
        sys.exit(f"ERROR: {error}")
