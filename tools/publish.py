class InvalidSite(ValueError):
    """An actionable manifest or managed-HTML validation failure."""


@dataclass
class FileSnapshot:
    path: Path
    contents: bytes | None
    mode: int | None

    @classmethod
    def read(cls, path, optional=False):
        try:
            metadata = path.lstat()
        except FileNotFoundError:
            if optional:
                return cls(path, None, None)
            raise InvalidSite(f"{path}: required file is missing")
        if not stat.S_ISREG(metadata.st_mode):
            raise InvalidSite(f"{path}: expected a readable regular file")
        return cls(path, path.read_bytes(), stat.S_IMODE(metadata.st_mode))

    def text(self):
        try:
            return self.contents.decode("utf-8")
        except UnicodeError as error:
            raise InvalidSite(f"{self.path}: expected UTF-8 text: {error}") from error


@dataclass
class Change:
    original: FileSnapshot
    desired: bytes | None

    def apply(self):
        path = self.original.path
        if self.desired is None:
            path.unlink()
            return
        temporary = path.with_name(f".{path.name}.{secrets.token_hex(8)}.tmp")
        try:
            # New gates use ordinary creation permissions: 0666 and the umask.
            descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o666)
            with os.fdopen(descriptor, "wb") as output:
                output.write(self.desired)
                if self.original.mode is not None:
                    os.fchmod(output.fileno(), self.original.mode)
            os.replace(temporary, path)
        finally:
            temporary.unlink(missing_ok=True)


def changed_files(desired_files):
    return [Change(original, desired) for original, desired in desired_files
            if original.contents != desired]


def unique_json_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise InvalidSite(f"posts.json: duplicate key {key!r}")
        result[key] = value
    return result


def load_manifest(snapshot):
    try:
        data = json.loads(snapshot.text(), object_pairs_hook=unique_json_object)
    except json.JSONDecodeError as error:
        raise InvalidSite(f"posts.json: {error}") from error

    def require(condition, location, expectation):
        if not condition:
            raise InvalidSite(f"posts.json: {location}: {expectation}")

    def identifier(value):
        return isinstance(value, str) and IDENTIFIER.fullmatch(value) is not None

    def text(value):
        return isinstance(value, str) and bool(value.strip())

    require(isinstance(data, dict), "root", "expected an object")
    labels = data.get("categories")
    require(isinstance(labels, dict), "categories", "expected an id-to-label object")
    for category, label in labels.items():
        require(identifier(category), f"categories.{category}", "expected a lowercase hyphenated identifier")
        require(text(label), f"categories.{category}", "expected a nonempty text label")
    posts = data.get("posts")
    require(isinstance(posts, list), "posts", "expected a list")
    slugs = set()
    for index, post in enumerate(posts):
        location = f"posts[{index}]"
        require(isinstance(post, dict), location, "expected an object")
        slug = post.get("slug")
        require(identifier(slug), f"{location}.slug", "expected a lowercase hyphenated single-segment slug")
        require(slug not in slugs, f"{location}.slug", f"duplicate slug {slug!r}")
        slugs.add(slug)
        for key in ("title", "date"):
            require(text(post.get(key)), f"{location}.{key} ({slug})", "expected nonempty text")
        require(post.get("status") in ("draft", "published"), f"{location}.status ({slug})",
                "expected exactly 'draft' or 'published'")
        categories = post.get("categories")
        require(isinstance(categories, list), f"{location}.categories ({slug})", "expected a list")
        seen = set()
        for category in categories:
            require(identifier(category), f"{location}.categories ({slug})", "expected category identifiers")
            require(category in labels, f"{location}.categories ({slug})", f"undeclared category {category!r}")
            require(category not in seen, f"{location}.categories ({slug})", f"duplicate category {category!r}")
            seen.add(category)
    return data


@dataclass(eq=False)
class Element:
    tag: str
    attrs: dict
    start: int
    start_end: int
    parent: "Element | None"
    children: list = field(default_factory=list)
    end_start: int | None = None

    def has_class(self, name):
        return name in (self.attrs.get("class") or "").split()


class Document(HTMLParser):
    """Index source spans; never serialize authored HTML through a DOM."""

    VOID_TAGS = set("area base br col embed hr img input link meta param source track wbr".split())

    def __init__(self, html, path):
        super().__init__(convert_charrefs=True)
        self.html = html
        self.path = path
        self.elements = []
        self.stack = []
        self.unmatched_heads = 0
        self.head_has_text = False
        self.lines = [0]
        # HTMLParser counts only LF, whereas splitlines also splits prose at
        # Unicode separators and bare CR, moving source spans into authored text.
        self.lines.extend(match.end() for match in re.finditer("\n", html))
        self.feed(html)
        self.close()

    def fail(self, message):
        raise InvalidSite(f"{self.path}: {message}")

    def source_offset(self):
        line, column = self.getpos()
        return self.lines[line - 1] + column

    def handle_starttag(self, tag, attrs):
        for key in ("id", "class", "name"):
            if sum(name == key for name, _ in attrs) > 1:
                self.fail(f"ambiguous duplicate {key} attribute on <{tag}>")
        start = self.source_offset()
        parent = self.stack[-1] if self.stack else None
        element = Element(tag, dict(attrs), start, start + len(self.get_starttag_text()), parent)
        self.elements.append(element)
        if parent:
            parent.children.append(element)
        if tag not in self.VOID_TAGS:
            self.stack.append(element)

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        if tag not in self.VOID_TAGS:
            self.stack.pop()

    def handle_endtag(self, tag):
        for index in range(len(self.stack) - 1, -1, -1):
            element = self.stack[index]
            if element.tag == tag:
                element.end_start = self.source_offset()
                del self.stack[index:]
                return
        if tag == "head":
            self.unmatched_heads += 1

    def handle_data(self, data):
        if self.stack and self.stack[-1].tag == "head" and data.strip(" \t\n\f\r"):
            self.head_has_text = True

    def require_closed(self, element, description):
        if element.end_start is None:
            self.fail(f"{description}: missing closing </{element.tag}>")
        return element

    def target(self, identifier, tag, class_name):
        matches = [node for node in self.elements if node.attrs.get("id") == identifier]
        if len(matches) != 1:
            self.fail(f"{identifier}: expected exactly one target, found {len(matches)}")
        node = matches[0]
        if node.tag != tag or not node.has_class(class_name):
            self.fail(f"{identifier}: expected <{tag}> with class {class_name}")
        return self.require_closed(node, identifier)

    def replace(self, spans):
        ordered = sorted(spans)
        if any(right[0] < left[1] for left, right in zip(ordered, ordered[1:])):
            self.fail("overlapping owned HTML targets; archive lists must be separate")
        result = self.html
        for start, end, replacement in reversed(ordered):
            result = result[:start] + replacement + result[end:]
        return result


def entry(post, labels, skip=None):
    tail = "".join(f' &middot; <a href="#{category}">{escape(labels[category])}</a>'
                   for category in post["categories"] if category != skip)
    return (
        "                <li>\n"
        f'                    <a href="/posts/{post["slug"]}/">{escape(post["title"])}</a><br>\n'
        f'                    {escape(post["date"])}{tail}\n'
        "                </li>\n"
    )


def archive_html(snapshot, data):
    document = Document(snapshot.text(), snapshot.path)
    chronological = document.target("chronological", "section", "archive-view-chrono")
    category_view = document.target("by-category", "section", "archive-view-category")
    chronological_lists = [node for node in chronological.children
                           if node.tag == "ul" and node.has_class("archive-list")]
    if len(chronological_lists) != 1:
        document.fail(f"chronological: expected exactly one archive-list, found {len(chronological_lists)}")
    targets = [(chronological_lists[0], None)]
    for category in data["categories"]:
        heading = document.target(category, "h3", "archive-category-heading")
        if heading.parent is not category_view:
            document.fail(f"{category}: heading must be directly inside by-category")
        siblings = category_view.children
        index = siblings.index(heading) + 1
        following = siblings[index] if index < len(siblings) else None
        if following is None or following.tag != "ul" or not following.has_class("archive-list"):
            document.fail(f"{category}: heading must be followed by its archive-list")
        targets.append((following, category))
    category_lists = [node for node in category_view.children
                      if node.tag == "ul" and node.has_class("archive-list")]
    if set(category_lists) != {node for node, category in targets if category is not None}:
        document.fail("by-category: ambiguous archive-list without a declared category heading")

    published = [post for post in data["posts"] if post["status"] == "published"]
    spans = []
    for listing, category in targets:
        document.require_closed(listing, category or "chronological")
        items = "".join(entry(post, data["categories"], category) for post in published
                        if category is None or category in post["categories"])
        spans.append((listing.start_end, listing.end_start, "\n" + items + "            "))
    return document.replace(spans).encode("utf-8")


def post_html(snapshot, draft):
    document = Document(snapshot.text(), snapshot.path)
    heads = [node for node in document.elements if node.tag == "head"]
    if len(heads) != 1 or document.unmatched_heads:
        document.fail(f"expected exactly one head with one closing tag, found {len(heads)} heads")
    head = document.require_closed(heads[0], "head")
    if head.parent is not None and head.parent.tag != "html":
        document.fail("head must be directly inside html")
    # Body content implicitly closes a browser's head, even when a later literal
    # </head> appears. Do not insert robots after that implicit closing point.
    metadata_tags = {"base", "link", "meta", "title", "style", "script", "noscript", "template"}
    if document.head_has_text or any(child.tag not in metadata_tags for child in head.children):
        document.fail("head must contain only metadata, comments and whitespace")
    for child in head.children:
        if child.tag not in document.VOID_TAGS:
            document.require_closed(child, f"head <{child.tag}>")
    if any(node.tag == "body" and node.start < head.end_start for node in document.elements):
        document.fail("head must end before body content starts")
    robots = [node for node in document.elements if node.tag == "meta"
              and (node.attrs.get("name") or "").strip().lower() == "robots"]
    if len(robots) > 1:
        document.fail("expected at most one robots meta tag")
    spans = []
    if robots:
        robot = robots[0]
        if robot.parent is not head:
            document.fail("robots meta tag must be directly inside head")
        spans.append((robot.start, robot.start_end, ROBOTS if draft else ""))
    elif draft:
        spans.append((head.end_start, head.end_start, ROBOTS))
    return document.replace(spans).encode("utf-8")


def parse_srcset(value):
    """Extract candidate URLs from an HTML srcset attribute."""
    urls = []
    parts = value.split(",")
    index = 0
    while index < len(parts):
        candidate = parts[index].strip()
        if candidate.startswith("data:") and index + 1 < len(parts) and not any(ch.isspace() for ch in candidate):
            candidate = candidate + "," + parts[index + 1].strip()
            index += 1
        index += 1
        if candidate:
            urls.append(candidate.split()[0])
    return urls


def extract_css_urls(css_text):
    """Yield URLs referenced inside CSS url(...) expressions, ignoring comments."""
    cleaned = CSS_COMMENT_RE.sub("", css_text)
    for match in CSS_URL_RE.finditer(cleaned):
        yield next(group for group in match.groups() if group is not None)


@dataclass(frozen=True)
class Reference:
    url: str
    is_page_link: bool
    allow_local_dir: bool


class ReferenceParser(HTMLParser):
    """Extract asset and link references from a post HTML file."""

    def __init__(self, html):
        super().__init__(convert_charrefs=True)
        self.references = []
        self._in_style = False
        self._style_chunks = []
        self.feed(html)
        self.close()

    def _add(self, url, is_page_link=False, allow_local_dir=False):
        self.references.append(Reference(url, is_page_link, allow_local_dir))

    def _add_css(self, css_text):
        for url in extract_css_urls(css_text):
            self._add(url)

    def handle_starttag(self, tag, attrs):
        attr_map = dict(attrs)
        rel_tokens = (attr_map.get("rel") or "").lower().split()
        for name, value in attrs:
            if value is None:
                continue
            if name in ("href", "xlink:href"):
                page_link = tag in ("a", "area") or (tag == "link" and "canonical" in rel_tokens)
                self._add(value, is_page_link=page_link, allow_local_dir=page_link)
            elif name == "src":
                self._add(value, allow_local_dir=(tag == "iframe"))
            elif name in ("poster", "data"):
                self._add(value)
            elif name == "srcset":
                for url in parse_srcset(value):
                    self._add(url)
            elif name == "style":
                self._add_css(value)
        if tag == "meta":
            self._handle_meta(attr_map)
        elif tag == "style":
            self._in_style = True
            self._style_chunks = []

    def _handle_meta(self, attr_map):
        content = attr_map.get("content")
        if content is None:
            return
        key = (attr_map.get("property") or attr_map.get("name") or "").strip().lower()
        if key in URL_META_KEYS:
            page_link = key in PAGE_META_KEYS
            self._add(content, is_page_link=page_link, allow_local_dir=page_link)
        elif (attr_map.get("http-equiv") or "").strip().lower() == "refresh":
            match = REFRESH_URL_RE.search(content.strip())
            if match:
                target = match.group(1).strip().strip("'\"")
                self._add(target, is_page_link=True, allow_local_dir=True)

    def handle_endtag(self, tag):
        if tag == "style" and self._in_style:
            self._add_css("".join(self._style_chunks))
            self._in_style = False
            self._style_chunks = []

    def handle_data(self, data):
        if self._in_style:
            self._style_chunks.append(data)


def decode_local_path(html_path, raw_url, path):
    """Percent-decode a local URL path and reject backslashes or null bytes."""
    decoded = unquote(path)
    if "\\" in path or "\\" in decoded or "\x00" in decoded:
        raise InvalidSite(f"{html_path}: invalid character in path {raw_url!r}")
    return decoded


def normalize_root_path(html_path, raw_url, path):
    """Decode and normalize a root-relative path, rejecting traversal."""
    decoded = decode_local_path(html_path, raw_url, path)
    segments = []
    for segment in decoded.split("/"):
        if segment in ("", "."):
            continue
        if segment == "..":
            raise InvalidSite(f"{html_path}: path traversal outside post directory in {raw_url!r}")
        segments.append(segment)
    trailing_slash = decoded.endswith("/") and bool(segments)
    return "/" + "/".join(segments) + ("/" if trailing_slash else "")


def verify_post_target(html_path, post_dir, parts, is_dir, allow_local_dir, raw_url):
    """Verify a target exists inside post_dir without escaping via symlinks."""
    resolved_post_dir = post_dir.resolve()
    candidate = post_dir
    for part in parts:
        candidate = candidate / part
        if candidate.is_symlink():
            raise InvalidSite(f"{html_path}: symlink target {raw_url!r} escapes post boundary rules")
    try:
        resolved_candidate = candidate.resolve()
    except OSError as error:
        raise InvalidSite(f"{html_path}: invalid local target {raw_url!r}: {error}") from error
    if not resolved_candidate.is_relative_to(resolved_post_dir):
        raise InvalidSite(f"{html_path}: target {raw_url!r} escapes /posts/{post_dir.name}/")

    try:
        metadata = candidate.lstat()
    except FileNotFoundError:
        raise InvalidSite(f"{html_path}: missing post-local target {raw_url!r}")

    if stat.S_ISDIR(metadata.st_mode):
        if not allow_local_dir:
            raise InvalidSite(f"{html_path}: asset reference {raw_url!r} points to a directory, not a file")
        index_file = candidate / "index.html"
        try:
            index_meta = index_file.lstat()
        except FileNotFoundError:
            raise InvalidSite(f"{html_path}: missing directory index for {raw_url!r}")
        if not stat.S_ISREG(index_meta.st_mode):
            raise InvalidSite(f"{html_path}: directory index for {raw_url!r} must be a regular file")
        return

    if is_dir:
        raise InvalidSite(f"{html_path}: directory reference {raw_url!r} does not resolve to a directory")
    if not stat.S_ISREG(metadata.st_mode):
        raise InvalidSite(f"{html_path}: post-local target {raw_url!r} must be a regular file")


def is_shared_chrome(path):
    return path in SHARED_CHROME_FILES or any(
        path.startswith(prefix) and len(path) > len(prefix) and not path.endswith("/")
        for prefix in SHARED_CHROME_PREFIXES
    )


def validate_root_relative(html_path, post_dir, slug, registered_slugs, raw_path, ref):
    """Validate a root-relative or same-site path against post boundaries and allowlists."""
    normalized = normalize_root_path(html_path, ref.url, raw_path)
    if normalized == "/static" or normalized.startswith("/static/"):
        raise InvalidSite(f"{html_path}: disallowed /static/ reference {ref.url!r}")

    post_prefix = f"/posts/{slug}"
    if normalized == post_prefix or normalized == f"{post_prefix}/":
        verify_post_target(html_path, post_dir, (), is_dir=True, allow_local_dir=ref.allow_local_dir, raw_url=ref.url)
        return
    if normalized.startswith(f"{post_prefix}/"):
        rel = normalized[len(f"{post_prefix}/"):]
        parts = [part for part in rel.split("/") if part]
        verify_post_target(
            html_path, post_dir, parts, is_dir=rel.endswith("/"),
            allow_local_dir=ref.allow_local_dir, raw_url=ref.url,
        )
        return

    if is_shared_chrome(normalized):
        return
    if normalized in SITE_ROUTES:
        if not ref.is_page_link:
            raise InvalidSite(f"{html_path}: asset reference {ref.url!r} cannot target site route")
        return

    if normalized.startswith("/posts/"):
        sub_parts = [part for part in normalized[len("/posts/"):].split("/") if part]
        is_registered_post_page = (
            ref.is_page_link
            and bool(sub_parts)
            and sub_parts[0] in registered_slugs
            and (len(sub_parts) == 1 or (len(sub_parts) == 2 and sub_parts[1] == "index.html" and not normalized.endswith("/")))
        )
        if is_registered_post_page:
            return
    raise InvalidSite(f"{html_path}: reference {ref.url!r} escapes /posts/{slug}/")


def validate_document_relative(html_path, post_dir, slug, raw_path, ref):
    """Resolve and verify a document-relative path stays inside post_dir."""
    decoded = decode_local_path(html_path, ref.url, raw_path)
    parts = list(html_path.parent.relative_to(post_dir).parts)
    for segment in decoded.split("/"):
        if segment in ("", "."):
            continue
        if segment == "..":
            if not parts:
                raise InvalidSite(f"{html_path}: path traversal outside /posts/{slug}/ in {ref.url!r}")
            parts.pop()
        else:
            parts.append(segment)
    is_dir = decoded.endswith("/") or decoded in (".", "..") or decoded.endswith(("/.", "/.."))
    verify_post_target(html_path, post_dir, parts, is_dir=is_dir, allow_local_dir=ref.allow_local_dir, raw_url=ref.url)


def validate_reference(html_path, post_dir, slug, registered_slugs, ref):
    """Validate one extracted URL reference from a post HTML file."""
    url = ref.url.strip()
    if not url:
        if not ref.is_page_link:
            raise InvalidSite(f"{html_path}: empty asset reference")
        return
    if url.startswith("#"):
        return
    try:
        parsed = urlsplit(url)
        host = (parsed.hostname or "").lower()
    except ValueError as error:
        raise InvalidSite(f"{html_path}: malformed URL {url!r}: {error}") from error

    scheme = parsed.scheme.lower()
    if scheme and scheme not in ALLOWED_SCHEMES:
        raise InvalidSite(f"{html_path}: disallowed URL scheme in {url!r}")
    if scheme and scheme not in ("http", "https"):
        return

    if parsed.netloc or scheme in ("http", "https"):
        if not host:
            raise InvalidSite(f"{html_path}: malformed URL {url!r}")
        if host in SAME_SITE_HOSTS:
            validate_root_relative(html_path, post_dir, slug, registered_slugs, parsed.path or "/", ref)
        elif not scheme and "." not in host:
            raise InvalidSite(f"{html_path}: disallowed protocol-relative target {url!r}")
        return

    if not parsed.path:
        return
    if parsed.path.startswith("/"):
        validate_root_relative(html_path, post_dir, slug, registered_slugs, parsed.path, ref)
    else:
        validate_document_relative(html_path, post_dir, slug, parsed.path, ref)


def post_html_files(post_dir):
    """Collect regular HTML files under post_dir without following symlinked directories."""
    if post_dir.is_symlink():
        raise InvalidSite(f"{post_dir}: expected a real post directory, not a symlink")
    files = []
    for dirpath, dirnames, filenames in os.walk(post_dir, followlinks=False):
        current = Path(dirpath)
        dirnames.sort()
        for dirname in dirnames:
            if (current / dirname).is_symlink():
                raise InvalidSite(f"{current / dirname}: symlinked directory inside post is not allowed")
        for filename in sorted(filenames):
            if filename.lower().endswith((".html", ".htm")):
                files.append(current / filename)
    return files


def validate_post_directory(post_dir, slug, registered_slugs, root_page):
    """Inspect all HTML files under post_dir for asset and link boundary violations."""
    root_path = post_dir / "index.html"
    for html_path in post_html_files(post_dir):
        snapshot = root_page if html_path == root_path else FileSnapshot.read(html_path)
        parser = ReferenceParser(snapshot.text())
        for ref in parser.references:
            validate_reference(html_path, post_dir, slug, registered_slugs, ref)


def desired_plan(data, manifest, status_changed):
    # All reads, validation and rendering finish before a caller can apply changes.
    archive = FileSnapshot.read(ARCHIVE)
    pages = [(archive, archive_html(archive, data))]
    registered_slugs = {post["slug"] for post in data["posts"]}
    gates = []
    removals = []
    for post in data["posts"]:
        directory = ROOT / "posts" / post["slug"]
        page = FileSnapshot.read(directory / "index.html")
        validate_post_directory(directory, post["slug"], registered_slugs, page)
        draft = post["status"] == "draft"
        pages.append((page, post_html(page, draft)))
        gate = FileSnapshot.read(directory / ".htaccess", optional=True)
        if draft:
            gates.append((gate, DRAFT_HTACCESS.encode("utf-8")))
        else:
            removals.append((gate, None))
    manifest_changes = []
    if status_changed:
        serialized = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
        manifest_changes.append((manifest, serialized.encode("utf-8")))
    return changed_files(gates + pages + manifest_changes + removals)


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "list"
    slug = sys.argv[2] if len(sys.argv) > 2 else None
    manifest = FileSnapshot.read(MANIFEST)
    data = load_manifest(manifest)
    index = {post["slug"]: post for post in data["posts"]}

    if cmd == "list":
        drafts = [post for post in data["posts"] if post["status"] == "draft"]
        print(f"{len(data['posts'])} posts, {len(drafts)} draft\n")
        for post in data["posts"]:
            mark = "DRAFT " if post["status"] == "draft" else "      "
            print(f"  {mark}{post['date']:<20} {post['title'][:52]}")
            print(f"        /posts/{post['slug']}/")
        return

    if cmd in ("status", "draft", "publish") and slug not in index:
        raise InvalidSite(f"unknown slug: {slug}")
    if cmd == "status":
        print(json.dumps(index[slug], indent=2))
        return
    if cmd not in ("build", "check", "draft", "publish"):
        sys.exit(__doc__)

    status_changed = False
    if cmd in ("draft", "publish"):
        status = "draft" if cmd == "draft" else "published"
        status_changed = index[slug]["status"] != status
        index[slug]["status"] = status
    plan = desired_plan(data, manifest, status_changed)
    if cmd == "check":
        if plan:
            raise InvalidSite(
                "STALE: the site does not match posts.json:\n"
                + "\n".join(f"  {change.original.path.relative_to(ROOT)}" for change in plan)
                + "\nRun: python3 tools/publish.py build"
            )
        print("site matches posts.json")
        return

    for change in plan:
        change.apply()
    print("\n".join(f"  updated {change.original.path.relative_to(ROOT)}" for change in plan)
          or "  already up to date")
    if cmd in ("draft", "publish"):
        print(f"{slug} is now {index[slug]['status']}")


if __name__ == "__main__":
    try:
        main()
    except (InvalidSite, OSError) as error:
        sys.exit(f"ERROR: {error}")
